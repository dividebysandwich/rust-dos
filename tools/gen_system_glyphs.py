"""Generate src/win32/gdi32/system16.rs, the glyphs the built-in Windows
draws the System font with at its 16-pixel size, the size of VGASYS.FON
at 96 dots an inch.

The glyphs are the 16-pixel bitmap strike of Wine's System font,
fonts/system.ttf in Wine's source (built from fonts/system.sfd),
Copyright (C) 2004 Huw D M Davies, Dmitry Timoshkov, under the GNU LGPL
2.1 or later. Run

    python tools/gen_system_glyphs.py WINE/fonts/system.ttf OUT

It needs fontTools (pip install fonttools) to read the strike. Each
glyph goes out as its character, its advance, its left column, its top
row (counted from the top of the 16-row cell, whose baseline is under
row 12) and its rows, each a u16 with the leftmost pixel in bit 15.
"""

import sys

from fontTools.ttLib import TTFont

HEIGHT = 16
ASCENT = 13

HEADER = """\
//! The glyphs of the System font's 16-pixel size, the size of
//! VGASYS.FON at 96 dots an inch: bold, two-pixel stems, 13 rows above
//! the baseline and 3 below. Generated by `tools/gen_system_glyphs.py`
//! from the 16-pixel bitmap strike of Wine's System font (Wine's
//! `fonts/system.sfd`), whose characters have VGASYS.FON's widths.
//!
//! Copyright (C) 2004 Huw D M Davies, Dmitry Timoshkov
//!
//! This library is free software; you can redistribute it and/or
//! modify it under the terms of the GNU Lesser General Public License
//! as published by the Free Software Foundation; either version 2.1 of
//! the License, or (at your option) any later version. Section 3 of
//! that licence lets rust-dos use it under the GNU General Public
//! License, version 2 or later.

/// The size's height in pixels.
pub const HEIGHT: usize = {height};

/// The glyphs, sorted by character: each the character, its advance,
/// its left column, its top row and its rows, the leftmost pixel in
/// bit 15.
#[rustfmt::skip]
pub(super) const GLYPHS: &[(u16, u8, u8, u8, &[u16])] = &[
"""

FOOTER = """];

fn entry(c: u16) -> Option<&'static (u16, u8, u8, u8, &'static [u16])> {
    GLYPHS
        .binary_search_by_key(&c, |g| g.0)
        .ok()
        .map(|i| &GLYPHS[i])
}

/// How far the character `c` moves on, if the font has it.
pub fn advance(c: u16) -> Option<i32> {
    entry(c).map(|g| g.1 as i32)
}

/// The glyph of the character `c` in a cell `width` columns wide, if the
/// font has it at that width: its rows, bit 0 the leftmost column.
pub fn glyph(c: u16, width: i32) -> Option<[u64; HEIGHT]> {
    let &(_, advance, left, top, rows) = entry(c)?;
    if advance as i32 != width {
        return None;
    }
    let mut out = [0u64; HEIGHT];
    for (y, &row) in rows.iter().enumerate() {
        out[top as usize + y] = (0..16)
            .filter(|x| row & (0x8000 >> x) != 0)
            .fold(0, |a, x| a | 1 << (left as u32 + x));
    }
    Some(out)
}
"""


def metric(m, *names):
    for n in names:
        if hasattr(m, n):
            return getattr(m, n)
    raise AttributeError(names[0])


def main(src, out):
    font = TTFont(src)
    cmap = font.getBestCmap()
    eblc, ebdt = font["EBLC"], font["EBDT"]
    (index,) = [
        i for i, s in enumerate(eblc.strikes) if s.bitmapSizeTable.ppemY == HEIGHT
    ]
    # Glyphs of image format 5 keep their metrics in the index.
    shared = {}
    for table in eblc.strikes[index].indexSubTables:
        if table.imageFormat == 5:
            for name in table.names:
                shared[name] = table.metrics
    strike = ebdt.strikeData[index]
    lines = []
    for cp in sorted(cmap):
        # Control characters and the private use area have nothing a code
        # page draws.
        if cp < 0x20 or cp > 0xFFFF or 0xE000 <= cp < 0xF900:
            continue
        name = cmap[cp]
        bitmap = strike.get(name)
        if bitmap is None:
            continue
        bitmap.decompile()
        m = shared.get(name) or bitmap.metrics
        width, height = m.width, m.height
        left = metric(m, "BearingX", "horiBearingX")
        top = ASCENT - metric(m, "BearingY", "horiBearingY")
        advance = metric(m, "Advance", "horiAdvance")
        rows = []
        for r in range(height):
            data = bitmap.getRow(r, bitDepth=1, metrics=m, reverseBytes=True)
            bits = 0
            for x in range(width):
                if data[x // 8] >> (x % 8) & 1:
                    bits |= 0x8000 >> x
            rows.append(bits)
        # Blank rows at the top and bottom carry nothing.
        while rows and rows[0] == 0:
            rows.pop(0)
            top += 1
        while rows and rows[-1] == 0:
            rows.pop()
        if not rows:
            top = 0
        if width > 16 or left < 0 or top < 0 or top + len(rows) > HEIGHT:
            print("U+%04X doesn't fit the cell, left out" % cp, file=sys.stderr)
            continue
        head = "    (0x%04X, %d, %d, %d, &[" % (cp, advance, left, top)
        words = ["0x%04X" % r for r in rows]
        line = head + ", ".join(words) + "]),"
        if len(line) <= 100:
            lines.append(line)
        else:
            # Ten rows a line keeps within 100 columns.
            lines.append(head)
            for i in range(0, len(words), 10):
                lines.append("        " + ", ".join(words[i : i + 10]) + ",")
            lines.append("    ]),")
    with open(out, "w", newline="\n") as f:
        f.write(HEADER.format(height=HEIGHT))
        f.write("\n".join(lines))
        f.write("\n")
        f.write(FOOTER)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit("usage: gen_system_glyphs.py WINE/fonts/system.ttf OUT")
    main(sys.argv[1], sys.argv[2])
