"""Generate src/win32/nls/tables.rs, the code page tables of the built-in
Windows, from the Unicode Consortium's mapping files.

The files are those of
https://www.unicode.org/Public/MAPPINGS/VENDORS/MICSFT/ (WINDOWS/CP125x.TXT
and PC/CPxxx.TXT). Download them into a folder and run

    python tools/gen_code_pages.py FOLDER src/win32/nls/tables.rs

Each table holds the characters of bytes 80h to FFh; bytes below 80h are
ASCII in every one of these code pages, which the script checks. A byte
the mapping file leaves undefined stands for the character of the same
number, as MultiByteToWideChar converts the undefined bytes 81h, 8Dh, 8Fh,
90h and 9Dh of code page 1252. Where another byte of the code page has
that character (code page 857's D5h, whose number is its E5h's Õ), the
undefined byte stands for U+F700 plus its number, in the private use
area, so that every byte converts to a character and back.
"""

import os
import sys

ANSI = [1250, 1251, 1252, 1253, 1254, 1257]
OEM = [437, 737, 775, 850, 852, 855, 857, 866, 869]
SUBDIR = {cp: "WINDOWS" for cp in ANSI} | {cp: "PC" for cp in OEM}


def read(path):
    table = {}
    for line in open(path, encoding="latin-1"):
        line = line.split("#")[0].strip()
        if not line.startswith("0x"):
            continue
        parts = line.split()
        byte = int(parts[0], 16)
        if len(parts) > 1:
            table[byte] = int(parts[1], 16)
    return table


def main(folder, path):
    out = open(path, "w", newline="\n")
    out.write("//! The code pages' tables: the characters of bytes 80h to FFh.\n")
    out.write("//! Generated by tools/gen_code_pages.py from the Unicode\n")
    out.write("//! Consortium's mapping files (MAPPINGS/VENDORS/MICSFT/WINDOWS\n")
    out.write("//! and MAPPINGS/VENDORS/MICSFT/PC); don't edit it by hand. A byte\n")
    out.write("//! a file leaves undefined stands for the character of its number,\n")
    out.write("//! or U+F700 plus it where another byte has that character.\n")
    out.write("\n")
    for cp in ANSI + OEM:
        table = read(os.path.join(folder, f"CP{cp}.TXT"))
        for b in range(0x80):
            assert table.get(b, b) == b, (cp, b)
        defined = set(table.values())
        high = [
            table.get(b, 0xF700 + b if b in defined else b) for b in range(0x80, 0x100)
        ]
        out.write(f"/// Code page {cp}, from {SUBDIR[cp]}/CP{cp}.TXT.\n")
        out.write("#[rustfmt::skip]\n")
        out.write(f"pub const CP{cp}: [u16; 128] = [\n")
        for i in range(0, 128, 8):
            row = ", ".join(f"0x{c:04X}" for c in high[i : i + 8])
            out.write(f"    {row},\n")
        out.write("];\n\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
