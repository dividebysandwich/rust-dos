"""Generate src/win32/nls/locales.rs, the locales of the built-in Windows,
from tools/locales.txt:

    python tools/gen_locales.py tools/locales.txt src/win32/nls/locales.rs

The output is formatted with rustfmt when it is on PATH. locales.txt's
header says where its values come from and how a block is written.

The file gets, for each locale, its GetLocaleInfo information (an Info),
its entry of LOCALES (locale id, code pages, character set, country code)
and its value of the `win32_locale` setting (a variant of Win32Locale, its
name, and its place among the values a saved state keeps), so that one
block in locales.txt is all a locale needs.
"""

import re
import shutil
import subprocess
import sys

STRINGS = [
    "full_language", "language", "abbrev_language", "native_language",
    "iso_language", "country", "abbrev_country", "native_country",
    "iso_country", "list", "measure", "decimal", "thousand", "grouping",
    "negative_number", "currency", "intl_symbol", "money_decimal",
    "money_thousand", "currency_order", "negative_currency",
    "date_separator", "time_separator", "short_date", "long_date",
    "time_format", "date_order", "hours24", "am", "pm", "first_day",
]
LISTS = {"days": 7, "abbrev_days": 7, "months": 12, "abbrev_months": 12}
OTHER = ["lcid", "code_pages", "country_code"]

# The character set of each ANSI code page.
CHARSETS = {
    1250: "EASTEUROPE_CHARSET",
    1251: "RUSSIAN_CHARSET",
    1252: "ANSI_CHARSET",
    1253: "GREEK_CHARSET",
    1254: "TURKISH_CHARSET",
    1257: "BALTIC_CHARSET",
}

def read(path):
    locales = []
    current = None
    for n, line in enumerate(open(path, encoding="utf-8"), 1):
        line = line.rstrip("\n")
        if not line.strip() or line.startswith("#"):
            continue
        m = re.fullmatch(r"\[([A-Za-z]{2}(-[A-Za-z]{4})?-[A-Za-z]{2})\]", line)
        if m:
            current = {"name": m.group(1)}
            locales.append(current)
            continue
        key, _, value = line.partition(" ")
        if current is None or key in current:
            sys.exit(f"{path}:{n}: {key} out of place")
        if key not in STRINGS and key not in LISTS and key not in OTHER:
            sys.exit(f"{path}:{n}: unknown field {key}")
        current[key] = value
    for loc in locales:
        missing = [k for k in STRINGS + list(LISTS) + OTHER if k not in loc]
        if missing:
            sys.exit(f"{loc['name']}: missing {', '.join(missing)}")
        for k, count in LISTS.items():
            items = loc[k].split("|")
            if len(items) != count:
                sys.exit(f"{loc['name']}: {k} has {len(items)} items, not {count}")
            loc[k] = items
        loc["lcid"] = int(loc["lcid"], 16)
        loc["code_pages"] = [int(x) for x in loc["code_pages"].split()]
        if loc["code_pages"][0] not in CHARSETS:
            sys.exit(f"{loc['name']}: no character set for {loc['code_pages'][0]}")
    names = [loc["name"].lower() for loc in locales]
    lcids = [loc["lcid"] for loc in locales]
    if len(set(names)) != len(names) or len(set(lcids)) != len(lcids):
        sys.exit("a name or a locale id is there twice")
    return locales


def variant(name):
    return "".join(p[0].upper() + p[1:].lower() for p in name.split("-"))


def const(name):
    return name.upper().replace("-", "_")


def string(value):
    return '"' + value.replace('"', '\\"') + '"'


def write(locales, out):
    w = out.write
    w("//! What GetLocaleInfo says of each locale of the built-in Windows: its\n")
    w("//! language's and country's names, and the formats of its numbers, money,\n")
    w("//! dates and times; each locale's ids and code pages (`LOCALES`); and the\n")
    w("//! values of the `win32_locale` setting (`Win32Locale`). The text is\n")
    w("//! Unicode here; GetLocaleInfoA gives it in the locale's code page.\n")
    w("//!\n")
    w("//! Generated by tools/gen_locales.py from tools/locales.txt, which says\n")
    w("//! where the values come from. Change that file, not this one.\n")
    w("//!\n")
    w("//! The names of the language and the country (LOCALE_SLANGUAGE and\n")
    w("//! LOCALE_SCOUNTRY) are the English ones, as an English Windows shows\n")
    w("//! them; a localized Windows shows them in its own language.\n\n")
    w("use super::{Locale, locale};\n")
    w("use super::{\n")
    w("    ANSI_CHARSET, BALTIC_CHARSET, EASTEUROPE_CHARSET, GREEK_CHARSET, RUSSIAN_CHARSET,\n")
    w("    TURKISH_CHARSET,\n")
    w("};\n\n")
    w("/// A locale's information.\n")
    w("pub struct Info {\n")
    w("    /// LOCALE_SLANGUAGE, LOCALE_SENGLANGUAGE, LOCALE_SABBREVLANGNAME,\n")
    w("    /// LOCALE_SNATIVELANGNAME and LOCALE_SISO639LANGNAME.\n")
    w("    pub full_language: &'static str,\n")
    w("    pub language: &'static str,\n")
    w("    pub abbrev_language: &'static str,\n")
    w("    pub native_language: &'static str,\n")
    w("    pub iso_language: &'static str,\n")
    w("    /// LOCALE_SENGCOUNTRY, LOCALE_SABBREVCTRYNAME, LOCALE_SNATIVECTRYNAME\n")
    w("    /// and LOCALE_SISO3166CTRYNAME.\n")
    w("    pub country: &'static str,\n")
    w("    pub abbrev_country: &'static str,\n")
    w("    pub native_country: &'static str,\n")
    w("    pub iso_country: &'static str,\n")
    w("    /// LOCALE_SLIST and LOCALE_IMEASURE (0 metric, 1 US).\n")
    w("    pub list: &'static str,\n")
    w("    pub measure: &'static str,\n")
    w("    /// Numbers: LOCALE_SDECIMAL, LOCALE_STHOUSAND, LOCALE_SGROUPING and\n")
    w("    /// LOCALE_INEGNUMBER.\n")
    w("    pub decimal: &'static str,\n")
    w("    pub thousand: &'static str,\n")
    w("    pub grouping: &'static str,\n")
    w("    pub negative_number: &'static str,\n")
    w("    /// Money: LOCALE_SCURRENCY, LOCALE_SINTLSYMBOL, LOCALE_SMONDECIMALSEP,\n")
    w("    /// LOCALE_SMONTHOUSANDSEP, LOCALE_ICURRENCY and LOCALE_INEGCURR.\n")
    w("    pub currency: &'static str,\n")
    w("    pub intl_symbol: &'static str,\n")
    w("    pub money_decimal: &'static str,\n")
    w("    pub money_thousand: &'static str,\n")
    w("    pub currency_order: &'static str,\n")
    w("    pub negative_currency: &'static str,\n")
    w("    /// Dates and times: LOCALE_SDATE, LOCALE_STIME, LOCALE_SSHORTDATE,\n")
    w("    /// LOCALE_SLONGDATE, LOCALE_STIMEFORMAT, LOCALE_IDATE (0 MDY, 1 DMY,\n")
    w("    /// 2 YMD), LOCALE_ITIME (0 12 hours, 1 24), LOCALE_S1159,\n")
    w("    /// LOCALE_S2359 and LOCALE_IFIRSTDAYOFWEEK (0 Monday, 6 Sunday).\n")
    for k in STRINGS[STRINGS.index("date_separator"):]:
        w(f"    pub {k}: &'static str,\n")
    w("    /// The days from Monday, and the months, and their abbreviations.\n")
    for k, count in LISTS.items():
        w(f"    pub {k}: [&'static str; {count}],\n")
    w("}\n\n")

    # The setting's values.
    w("/// The system locale of the built-in Windows (`win32_locale`): the\n")
    w("/// localized Windows 98 it is, which sets its ANSI and OEM code pages,\n")
    w("/// its locale's information and formats, and its fonts' character set.\n")
    w("#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash)]\n")
    w("pub enum Win32Locale {\n")
    for i, loc in enumerate(locales):
        ansi, oem, _ = loc["code_pages"]
        w(f"    /// {loc['full_language']}, {loc['country']}: code pages {ansi} and {oem}.\n")
        if i == 0:
            w("    #[default]\n")
        w(f"    {variant(loc['name'])},\n")
    w("}\n\n")
    w("impl Win32Locale {\n")
    w("    /// Every value, in the order a saved state numbers them.\n")
    w(f"    pub const ALL: [Win32Locale; {len(locales)}] = [\n")
    for loc in locales:
        w(f"        Self::{variant(loc['name'])},\n")
    w("    ];\n\n")
    w("    /// \"en-US\", \"ru-RU\", ...\n")
    w("    pub fn name(self) -> &'static str {\n")
    w("        match self {\n")
    for loc in locales:
        w(f"            Self::{variant(loc['name'])} => {string(loc['name'])},\n")
    w("        }\n")
    w("    }\n")
    w("}\n\n")
    w("crate::state_enum!(Win32Locale {\n")
    for loc in locales:
        w(f"    Win32Locale::{variant(loc['name'])},\n")
    w("});\n\n")

    w("/// The locales, the default first.\n")
    w(f"pub const LOCALES: [Locale; {len(locales)}] = [\n")
    for loc in locales:
        ansi, oem, mac = loc["code_pages"]
        w("    locale(\n")
        w(f"        Win32Locale::{variant(loc['name'])},\n")
        w(f"        0x{loc['lcid']:04X},\n")
        w(f"        ({ansi}, {oem}, {mac}),\n")
        w(f"        {CHARSETS[ansi]},\n")
        w(f"        {loc['country_code']},\n")
        w(f"        &{const(loc['name'])},\n")
        w("    ),\n")
    w("];\n")

    for loc in locales:
        w(f"\npub const {const(loc['name'])}: Info = Info {{\n")
        for k in STRINGS:
            w(f"    {k}: {string(loc[k])},\n")
        for k in LISTS:
            items = ", ".join(string(x) for x in loc[k])
            w(f"    {k}: [{items}],\n")
        w("};\n")


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    locales = read(sys.argv[1])
    with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as out:
        write(locales, out)
    if shutil.which("rustfmt"):
        subprocess.run(["rustfmt", "--edition", "2024", sys.argv[2]], check=True)


main()
