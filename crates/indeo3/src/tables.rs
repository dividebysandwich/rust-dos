/// Remaps a pixel for a quant index, so adding the deltas of a table with
/// a coarser step can't overflow 7 bits.
pub(crate) static REQUANT_TAB: [[u8; 128]; 8] = build_requant_tab();

const fn build_requant_tab() -> [[u8; 128]; 8] {
    const OFFSETS: [i32; 8] = [1, 1, 2, -3, -3, 3, 4, 4];
    const DELTAS: [i32; 8] = [0, 1, 0, 4, 4, 1, 0, 1];
    let mut tab = [[0; 128]; 8];
    let mut i = 0;
    while i < 8 {
        let step = i as i32 + 2;
        let mut j = 0;
        while j < 128 {
            // C's division truncates toward zero, as Rust's does.
            let v = (j as i32 + OFFSETS[i]) / step * step + DELTAS[i];
            tab[i][j] = v as u8;
            j += 1;
        }
        i += 1;
    }
    // The last entries above come out at 128 or more; pixels stay below
    // 128, so they get the highest value of the section's step.
    tab[0][127] = 126;
    tab[1][119] = 118;
    tab[1][120] = 118;
    tab[2][126] = 124;
    tab[2][127] = 124;
    tab[6][124] = 120;
    tab[6][125] = 120;
    tab[6][126] = 120;
    tab[6][127] = 120;
    // As Intel's decoders have them.
    tab[1][7] = 10;
    tab[4][8] = 10;
    tab
}
