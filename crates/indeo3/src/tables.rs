/// One entry of a compressed table, as FFmpeg's macros write them: a pair
/// of deltas (a, b), with E2 adding (-a, -b) and E4 also (b, a) and
/// (-b, -a).
#[derive(Clone, Copy)]
enum Entry {
    Pd(i8, i8),
    E2(i8, i8),
    E4(i8, i8),
}

use Entry::{E2, E4, Pd};

/// The table's pairs, in order, padded with (0, 0) to `N` as C pads a
/// shorter initializer.
const fn expand<const N: usize>(src: &[Entry]) -> [(i8, i8); N] {
    let mut out = [(0, 0); N];
    let mut i = 0;
    let mut n = 0;
    while i < src.len() {
        match src[i] {
            Pd(a, b) => {
                out[n] = (a, b);
                n += 1;
            }
            E2(a, b) => {
                out[n] = (a, b);
                out[n + 1] = (-a, -b);
                n += 2;
            }
            E4(a, b) => {
                out[n] = (a, b);
                out[n + 1] = (-a, -b);
                out[n + 2] = (b, a);
                out[n + 3] = (-b, -a);
                n += 4;
            }
        }
        i += 1;
    }
    out
}

/// The pairs as 16-bit words for the 4x4 modes: `a` in the low byte, `b`
/// in the high one, added to two little-endian pixels at once.
const fn deltas<const N: usize>(p: &[(i8, i8); N]) -> [u16; N] {
    let mut out = [0; N];
    let mut i = 0;
    while i < N {
        out[i] = (p[i].1 as i32 * 256 + p[i].0 as i32) as u16;
        i += 1;
    }
    out
}

/// The pairs as 32-bit words for the 8x8 modes, each delta used twice:
/// a, a, b, b from the low byte up.
const fn deltas_m10<const N: usize>(p: &[(i8, i8); N]) -> [u32; N] {
    let mut out = [0; N];
    let mut i = 0;
    while i < N {
        let (a, b) = (p[i].0 as i32, p[i].1 as i32);
        out[i] = (b * (1 << 24) + b * (1 << 16) + a * (1 << 8) + a) as u32;
        i += 1;
    }
    out
}

macro_rules! table {
    ($t:ident, $m:ident, $n:literal, [$($e:expr),* $(,)?]) => {
        static $t: [u16; $n] = deltas(&expand::<$n>(&[$($e),*]));
        static $m: [u32; $n] = deltas_m10(&expand::<$n>(&[$($e),*]));
    };
}

