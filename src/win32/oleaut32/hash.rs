//! LHashValOfNameSys and LHashValOfNameSysA: the hash of a name that
//! type libraries keep with it and ITypeComp::Bind takes, as Wine's
//! oleaut32/hash.c makes it (LGPL 2.1 or later). The high word is the
//! system and the locale's group, the low word a hash of the name's
//! characters, each first put through the group's table, which folds
//! case and accents.
//!
//! Copyright 1999 Corel Corporation
//! Copyright 2001-2003 Jon Griffiths

use crate::cpu::Cpu;

/// SYSKIND's SYS_MAC: the characters past 7Fh are the Mac's.
const SYS_MAC: u32 = 2;

/// The hash of `name`'s bytes for the system `kind` and the locale
/// `lcid` (one ConvertDefaultLocale has made specific).
pub fn hash(kind: u32, lcid: u32, name: &[u8]) -> u32 {
    let mac = u32::from(kind == SYS_MAC);
    let language = lcid & 0x3FF;
    let sublanguage = lcid >> 10 & 0x3F;
    let (offset, table): (u32, &[u8; 384]) = match language {
        // Czech, Hungarian, Polish, Slovak, Spanish.
        0x05 | 0x0E | 0x15 | 0x1B | 0x0A => (32, &LOOKUP_32),
        0x0D => (48, &LOOKUP_48),
        0x11 => (64, &LOOKUP_64),
        0x12 => (80, &LOOKUP_80),
        0x04 => (112, &LOOKUP_112),
        0x08 => (128, &LOOKUP_128),
        0x0F => (144, &LOOKUP_144),
        0x1F => (160, &LOOKUP_160),
        // Norwegian (Nynorsk).
        0x14 if sublanguage == 2 => (176, &LOOKUP_176),
        // Arabic, Farsi.
        0x01 | 0x29 => (208, &LOOKUP_208),
        0x19 => (224, &LOOKUP_224),
        _ => (16, &LOOKUP_16),
    };
    let mut low: u32 = 0x0DEA_DBEE;
    for &c in name {
        let i = if c > 0x7F && mac != 0 {
            c as usize + 0x80
        } else {
            c as usize
        };
        low = low.wrapping_mul(37).wrapping_add(table[i] as u32);
    }
    (offset | mac) << 16 | (low % 65599) & 0xFFFF
}

/// The bytes of the string at `at` up to its zero, of `width` bytes a
/// character; None if it can't be read.
fn string_at(cpu: &mut Cpu, at: u32, width: u32) -> Option<Vec<u32>> {
    let mut chars = Vec::new();
    loop {
        let p = at.checked_add(width * chars.len() as u32)?;
        if !cpu.bus.guest_probe(p, width as usize, false) {
            return None;
        }
        let c = if width == 1 {
            cpu.bus.guest_read_8(p) as u32
        } else {
            cpu.bus.guest_read_16(p) as u32
        };
        if c == 0 {
            return Some(chars);
        }
        chars.push(c);
    }
}

/// LHashValOfNameSysA(kind, lcid, name): 0 for no name.
pub fn lhash_val_of_name_sys_a(cpu: &mut Cpu, args: &[u32]) -> Option<u32> {
    let &[kind, lcid, name] = args else {
        unreachable!()
    };
    if name == 0 {
        return Some(0);
    }
    let Some(chars) = string_at(cpu, name, 1) else {
        return Some(0);
    };
    let bytes: Vec<u8> = chars.into_iter().map(|c| c as u8).collect();
    let lcid = crate::win32::nls::convert_default(cpu, lcid);
    Some(hash(kind, lcid, &bytes))
}

/// LHashValOfNameSys(kind, lcid, name): the name, of Unicode characters,
/// in the ANSI code page first.
pub fn lhash_val_of_name_sys(cpu: &mut Cpu, args: &[u32]) -> Option<u32> {
    let &[kind, lcid, name] = args else {
        unreachable!()
    };
    if name == 0 {
        return Some(0);
    }
    let Some(chars) = string_at(cpu, name, 2) else {
        return Some(0);
    };
    let units: Vec<u16> = chars.into_iter().map(|c| c as u16).collect();
    let bytes = crate::win32::nls::ansi(cpu).encode(&units);
    let lcid = crate::win32::nls::convert_default(cpu, lcid);
    Some(hash(kind, lcid, &bytes))
}

