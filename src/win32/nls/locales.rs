//! What GetLocaleInfo says of each locale of the built-in Windows: its
//! language's and country's names, and the formats of its numbers, money,
//! dates and times, as Windows' national language data has them. The text
//! is Unicode here; GetLocaleInfoA gives it in the locale's code page.
//!
//! The names of the language and the country (LOCALE_SLANGUAGE and
//! LOCALE_SCOUNTRY) are the English ones, as an English Windows shows
//! them; a localized Windows shows them in its own language.

/// A locale's information.
pub struct Info {
    /// LOCALE_SENGLANGUAGE, LOCALE_SABBREVLANGNAME, LOCALE_SNATIVELANGNAME
    /// and LOCALE_SISO639LANGNAME.
    pub language: &'static str,
    pub abbrev_language: &'static str,
    pub native_language: &'static str,
    pub iso_language: &'static str,
    /// LOCALE_SENGCOUNTRY, LOCALE_SABBREVCTRYNAME, LOCALE_SNATIVECTRYNAME
    /// and LOCALE_SISO3166CTRYNAME.
    pub country: &'static str,
    pub abbrev_country: &'static str,
    pub native_country: &'static str,
    pub iso_country: &'static str,
    /// LOCALE_SLIST and LOCALE_IMEASURE (0 metric, 1 US).
    pub list: &'static str,
    pub measure: &'static str,
    /// Numbers: LOCALE_SDECIMAL, LOCALE_STHOUSAND, LOCALE_SGROUPING and
    /// LOCALE_INEGNUMBER.
    pub decimal: &'static str,
    pub thousand: &'static str,
    pub grouping: &'static str,
    pub negative_number: &'static str,
    /// Money: LOCALE_SCURRENCY, LOCALE_SINTLSYMBOL, LOCALE_SMONDECIMALSEP,
    /// LOCALE_SMONTHOUSANDSEP, LOCALE_ICURRENCY and LOCALE_INEGCURR.
    pub currency: &'static str,
    pub intl_symbol: &'static str,
    pub money_decimal: &'static str,
    pub money_thousand: &'static str,
    pub currency_order: &'static str,
    pub negative_currency: &'static str,
    /// Dates and times: LOCALE_SDATE, LOCALE_STIME, LOCALE_SSHORTDATE,
    /// LOCALE_SLONGDATE, LOCALE_STIMEFORMAT, LOCALE_IDATE (0 MDY, 1 DMY,
    /// 2 YMD), LOCALE_ITIME (0 12 hours, 1 24), LOCALE_S1159,
    /// LOCALE_S2359 and LOCALE_IFIRSTDAYOFWEEK (0 Monday, 6 Sunday).
    pub date_separator: &'static str,
    pub time_separator: &'static str,
    pub short_date: &'static str,
    pub long_date: &'static str,
    pub time_format: &'static str,
    pub date_order: &'static str,
    pub hours24: &'static str,
    pub am: &'static str,
    pub pm: &'static str,
    pub first_day: &'static str,
    /// The days from Monday, and the months, and their abbreviations.
    pub days: [&'static str; 7],
    pub abbrev_days: [&'static str; 7],
    pub months: [&'static str; 12],
    pub abbrev_months: [&'static str; 12],
}

