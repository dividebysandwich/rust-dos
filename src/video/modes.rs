//! The register values the IBM VGA BIOS loads for each standard video mode
//! (its video parameter table): Miscellaneous Output, sequencer, CRTC,
//! graphics controller and attribute controller.

use super::VideoMode;

pub struct VgaModeRegs {
    pub misc: u8,
    /// Sequencer registers 01h-04h (00h is the reset register).
    pub seq: [u8; 4],
    /// CRTC registers 00h-18h.
    pub crtc: [u8; 25],
    /// Graphics controller registers 00h-08h.
    pub gc: [u8; 9],
    /// Attribute controller registers: 16 palette entries, then 10h-14h.
    pub attr: [u8; 21],
}

