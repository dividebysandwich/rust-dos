#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_three_64_colour_tables() {
        // rgbRGB: 14h is brown, 38h-3Fh the bright colours.
        assert_eq!(DacTable::Ega.color(0x14), [0x2A, 0x15, 0x00]);
        assert_eq!(DacTable::Ega.color(0x39), [0x15, 0x15, 0x3F]);
        assert_eq!(DacTable::Ega.color(0x3F), [0x3F; 3]);
        // A CGA monitor: bit 4 is the intensity, 06h brown, 16h yellow.
        assert_eq!(DacTable::Cga.color(0x06), [0x2A, 0x15, 0x00]);
        assert_eq!(DacTable::Cga.color(0x10), [0x15; 3]);
        assert_eq!(DacTable::Cga.color(0x16), [0x3F, 0x3F, 0x15]);
        assert_eq!(DacTable::Cga.color(0x13), [0x15, 0x3F, 0x3F]);
        assert_eq!(DacTable::Cga.color(0x2B), DacTable::Cga.color(0x03));
        // Monochrome: black, normal, dim and bright.
        assert_eq!([0x00, 0x08, 0x10, 0x18].map(|i| DacTable::Mono.color(i)[0]), [0x00, 0x2A, 0x15, 0x3F]);
    }

    #[test]
    fn the_first_16_colours_of_the_256_are_the_cga_ones() {
        for color in 0..16u8 {
            assert_eq!(DacTable::Vga256.color(color), rgbi(color), "colour {}", color);
        }
    }

    #[test]
    fn loading_keeps_the_rest_of_the_256() {
        let mut dac = [0u8; 768];
        DacTable::Cga.load(&mut dac);
        assert_eq!(dac[0x10 * 3..0x11 * 3], [0x15; 3]);
        assert_eq!(dac[64 * 3..], VGA_DEFAULT_PALETTE[64 * 3..]);
    }
}
