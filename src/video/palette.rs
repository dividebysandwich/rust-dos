//! The colour tables the IBM VGA BIOS loads into the DAC at a mode set.
//! In the 16-colour and text modes the attribute controller's palette
//! registers pick one of the first 64 DAC entries, and which 64 colours
//! those are depends on the monitor the mode was made for: the EGA's
//! rgbRGB colours, a CGA monitor's 16 or a monochrome monitor's shades.

use super::VideoMode;

/// Which table a mode's DAC gets.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DacTable {
    /// The EGA's 64 colours, rgbRGB (secondary red, green and blue at a
    /// third, primary at two thirds): the text modes and the 350- and
    /// 480-line 16-colour modes.
    Ega,
    /// A CGA monitor's 16 colours, for the 200-line graphics modes: bits
    /// 0-2 are blue, green and red, bit 4 the intensity, and dark yellow is
    /// brown, as the IBM 5153 monitor shows it.
    Cga,
    /// A monochrome monitor's shades: bit 3 is the video, bit 4 the
    /// intensity.
    Mono,
    /// Mode 13h's 256 colours.
    Vga256,
}

impl DacTable {
    /// The table the BIOS loads for `mode`.
    pub fn for_mode(mode: VideoMode) -> Self {
        match mode {
            VideoMode::Cga320x200Color
            | VideoMode::Cga320x200
            | VideoMode::Cga640x200
            | VideoMode::Ega320x200
            | VideoMode::Ega640x200 => DacTable::Cga,
            VideoMode::Graphics320x200 | VideoMode::Vesa => DacTable::Vga256,
            VideoMode::Mono80x25 => DacTable::Mono,
            _ => DacTable::Ega,
        }
    }

    /// Entry `index` (0-63) in 6-bit DAC values.
    pub fn color(self, index: u8) -> [u8; 3] {
        match self {
            DacTable::Ega => {
                let level =
                    |primary: u8, secondary: u8| ((index >> primary) & 1) * 0x2A + ((index >> secondary) & 1) * 0x15;
                [level(2, 5), level(1, 4), level(0, 3)]
            }
            DacTable::Cga => rgbi((index & 0x07) | (index >> 1 & 0x08)),
            DacTable::Mono => {
                let shade = [0x00, 0x2A, 0x15, 0x3F][(index >> 3 & 3) as usize];
                [shade; 3]
            }
            DacTable::Vga256 => {
                let i = index as usize * 3;
                [VGA_DEFAULT_PALETTE[i], VGA_DEFAULT_PALETTE[i + 1], VGA_DEFAULT_PALETTE[i + 2]]
            }
        }
    }

    /// Load the DAC (256 entries of red, green and blue) as the BIOS does
    /// for a mode: the whole 256-colour palette, then this table over its
    /// first 64 entries.
    pub fn load(self, dac: &mut [u8]) {
        dac.copy_from_slice(&VGA_DEFAULT_PALETTE);
        if self != DacTable::Vga256 {
            for index in 0..64u8 {
                let i = index as usize * 3;
                dac[i..i + 3].copy_from_slice(&self.color(index));
            }
        }
    }
}

/// One of the 16 colours of a CGA monitor, in 6-bit DAC values: bits 0-2
/// blue, green and red at two thirds, bit 3 adding a third to all three.
/// Dark yellow is brown: the monitor halves its green.
pub fn rgbi(color: u8) -> [u8; 3] {
    let intensity = if color & 0x08 != 0 { 0x15 } else { 0 };
    let level = |bit: u8| ((color >> bit) & 1) * 0x2A + intensity;
    let green = if color & 0x0F == 0x06 { 0x15 } else { level(1) };
    [level(2), green, level(0)]
}

